int btstack_at_command_get_domain(
    btstack_at_command_id_t id,
    btstack_at_command_domain_t *domain)
{
    uint16_t index;

    if (domain == NULL) {
        return BTSTACK_AT_STATUS_INVALID_ARGUMENT;
    }
    for (index = 0u;
         index < (sizeof(btstack_at_dispatch_entries) /
                  sizeof(btstack_at_dispatch_entries[0]));
         index++) {
        if (btstack_at_dispatch_entries[index].id == id) {
            *domain = btstack_at_dispatch_entries[index].domain;
            return BTSTACK_AT_STATUS_OK;
        }
    }
    return BTSTACK_AT_STATUS_INVALID_ARGUMENT;
}
