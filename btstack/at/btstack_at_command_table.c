static int btstack_at_command_name_equal(
    const char *left,
    const char *right,
    uint16_t length)
{
    uint16_t index;

    for (index = 0u; index < length; index++) {
        if (left[index] != right[index]) {
            return 0;
        }
    }
    return 1;
}

const btstack_at_command_descriptor_t *btstack_at_command_find(
    const char *name,
    uint16_t name_length)
{
    uint16_t index;

    if ((name == NULL) || (name_length == 0u)) {
        return NULL;
    }
    for (index = 0u;
         index < (sizeof(btstack_at_command_descriptors) /
                  sizeof(btstack_at_command_descriptors[0]));
         index++) {
        const btstack_at_command_descriptor_t *descriptor =
            &btstack_at_command_descriptors[index];
        if ((name_length == descriptor->name_length) &&
            btstack_at_command_name_equal(
                name,
                descriptor->name,
                name_length)) {
            return descriptor;
        }
    }
    return NULL;
}
