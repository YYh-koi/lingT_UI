INT8U* jpeg_header_generate(INT32U yuv_fmt, INT32U quality, INT16U width, INT16U height, INT32U fifo_line)
{
	INT16U *plum, *pchr, size;
	INT32S i;
	INT8U* addr;

	size = sizeof(jpeg_422_header);

	addr = gp_malloc(size);

	if (!addr)
		return NULL;

	gp_memcpy((INT8S*)addr, (INT8S*)jpeg_422_header, size);

	if (quality < 25) {
		plum = (INT16U *)quant20_luminance_table;
		pchr = (INT16U *)quant20_chrominance_table;
	}
	else if (quality < 30) {
		plum = (INT16U *)quant25_luminance_table;
		pchr = (INT16U *)quant25_chrominance_table;
	}
	else if (quality < 40) {
		plum = (INT16U *)quant30_luminance_table;
		pchr = (INT16U *)quant30_chrominance_table;
	}
	else if (quality < 50) {
		plum = (INT16U *)quant40_luminance_table;
		pchr = (INT16U *)quant40_chrominance_table;
	}
	else if (quality < 65) {
		plum = (INT16U *)quant50_luminance_table;
		pchr = (INT16U *)quant50_chrominance_table;
	}
	else if (quality < 70) {
		plum = (INT16U *)quant65_luminance_table;
		pchr = (INT16U *)quant65_chrominance_table;
	}
	else if (quality < 80) {
		plum = (INT16U *)quant70_luminance_table;
		pchr = (INT16U *)quant70_chrominance_table;
	}
	else if (quality < 85) {
		plum = (INT16U *)quant80_luminance_table;
		pchr = (INT16U *)quant80_chrominance_table;
	}
	else if (quality < 90) {
		plum = (INT16U *)quant85_luminance_table;
		pchr = (INT16U *)quant85_chrominance_table;
	}
	else if (quality < 93) {
		plum = (INT16U *)quant90_luminance_table;
		pchr = (INT16U *)quant90_chrominance_table;
	}
	else if (quality < 95) {
		plum = (INT16U *)quant93_luminance_table;
		pchr = (INT16U *)quant93_chrominance_table;
	}
	else if (quality < 98) {
		plum = (INT16U *)quant95_luminance_table;
		pchr = (INT16U *)quant95_chrominance_table;
	}
	else if (quality < 100) {
		plum = (INT16U *)quant98_luminance_table;
		pchr = (INT16U *)quant98_chrominance_table;
	}

	if (quality >= 100) {
		//Luminance
		for(i=0; i<64; i++)
			addr[0x24+i] = 0x01;

		//Chrominance
		for(i=0; i<64; i++)
			addr[0x69+i] = 0x01;
	} else {
		//Luminance
		for(i=0; i<64; i++)
			addr[0x24+i] = (INT8U) (*(plum + zigzag_scan[i]) & 0xFF);

		//Chrominance
		for(i=0; i<64; i++)
			addr[0x69+i] = (INT8U) (*(pchr + zigzag_scan[i]) & 0xFF);
	}

	addr[0xAE] = height >> 8;
	addr[0xAF] = height & 0xFF;
	addr[0xB0] = width >> 8;
	addr[0xB1] = width & 0xFF;

	if(yuv_fmt == JPEG_YUV422) {
		addr[0xB4] = JPEG_IMG_FORMAT_422;
		addr[0x270] = ((width*fifo_line >> 7) & 0xFF00) >> 8;
		addr[0x271] = ((width*fifo_line >> 7) & 0x00FF);
	} else if(yuv_fmt == JPEG_YUV420) {
		addr[0xB4] = JPEG_IMG_FORMAT_420;
		addr[0x270] = ((width*fifo_line >> 8) & 0xFF00) >> 8;
		addr[0x271] = ((width*fifo_line >> 8) & 0x00FF);
	}

	return addr;
}

/**
 * @brief   update quality of jpeg header
 * @param   header:				pointer to header buffer
 * @param   Y_quality_value:	Y quality value
 * @param   UV_quality_value:	UV quality value
 * @return  none
 */
void jpeg_header_quality_set(JPEG_IDX idx, INT8U* header, INT8U Y_quality_value,INT8U UV_quality_value)
{
	if (!header)
		return;
	// Y
	jpeg_header_quantization_table_calculate(idx, ENUM_JPEG_LUMINANCE_QTABLE, Y_quality_value, header + 0x24);
	// UV
	jpeg_header_quantization_table_calculate(idx, ENUM_JPEG_CHROMINANCE_QTABLE, UV_quality_value, header + 0x69);
}

INT8U *jpeg_header_get_addr(void)
{
	return &jpeg_422_header[0];
}

INT32U jpeg_header_get_size(void)
{
	return C_JPEG_HEADER_SIZE;
}

