{
#if TP9950_I2C_MODE == SENSOR_I2C_MODE_SW
	INT16U	data;
	if(drv_l2_sccb_read(tp9950_handle, reg, &data) >= 0)
	{
		*value = (INT16U) data;
		//DBG_PRINT("0x%02x, 0x%02x\r\n", reg, *value);
		return STATUS_OK;
	}
	else
	{
		*value = 0xFF;
		DBG_PRINT("sccb_read fail...\r\n");
		return STATUS_FAIL;
	}

#elif TP9950_I2C_MODE == SENSOR_I2C_MODE_HW
	INT8U	value = 0;
	if(drv_l1_reg_1byte_data_1byte_read(&tp9950_handle, reg, &value) >= 0)
	{
		//DBG_PRINT("0x%02x, 0x%02x\r\n", reg, value);
		return STATUS_OK;
	}
	else
	{
		DBG_PRINT("sccb_read fail...\r\n");
		return STATUS_FAIL;
	}
#endif
}

static INT32S tp9950_sccb_write_table(regval8_t *pTable)
{
    INT32U retry_cnt = 0;
	//INT32S ai_ret;
	while(1)
	{
		if(pTable->reg_num == 0xff && pTable->value == 0xff)
		{
			break;
		}
        	//DBG_PRINT("W:reg = 0x%x, val = 0x%x\r\n", pTable->reg_num, pTable->value);
		if(tp9950_sccb_write(pTable->reg_num, pTable->value) < 0)
		{
			DBG_PRINT("%s: sccb write fail: reg = 0x%x, val = 0x%x\r\n", __FUNCTION__, pTable->reg_num, pTable->value);
			retry_cnt += 1;
			if(retry_cnt >= 10)
				return STATUS_FAIL;
			continue;
		}
		/*
		ai_ret = tp9950_sccb_read(pTable->reg_num, &ai_value);
		DBG_PRINT("R:reg = 0x%x, val = 0x%x, ret=%d\r\n", pTable->reg_num, ai_value,ai_ret);
		*/
		pTable++;

	}

	return STATUS_OK;
}

void tp9950_csi_dvp_init(void)
{
	DBG_PRINT("%s\r\n", __func__);

	// reguest sccb
	tp9950_sccb_open();

	drv_l1_csi_init(TP9950_CSI_DEV);

#ifdef BACK_SENSOR_RESET
	gpio_set_port_attribute(BACK_SENSOR_RESET, ATTRIBUTE_HIGH);
	gpio_init_io(BACK_SENSOR_RESET, GPIO_OUTPUT);
	gpio_write_io(BACK_SENSOR_RESET, DATA_HIGH);
	osDelay(100);
	gpio_write_io(BACK_SENSOR_RESET, DATA_LOW);
	osDelay(200);
	gpio_write_io(BACK_SENSOR_RESET, DATA_HIGH);
	osDelay(100);
#endif

}

/**
 * @brief   un-initialization function
 * @param   sensor format parameters
 * @return 	none
 */
void tp9950_csi_dvp_uninit(void)
{
	// disable mclk
	drv_l2_sensor_set_mclkout(MCLK_NONE,TP9950_CSI_DEV);

	drv_l2_csi_stop(TP9950_CSI_DEV);

	// release sccb
	tp9950_sccb_close();
	drv_l1_csi_uninit(TP9950_CSI_DEV);

}

/**
 * @brief   stream start function
 * @param   info index
 *
 * @return 	none
 */
void tp9950_csi_dvp_stream_start(INT32U index, INT32U bufA, INT32U bufB)
{
	gpCSIPara_t csi_Para;

	gp_memset((INT8S *)&csi_Para, 0, sizeof(gpCSIPara_t));

	/* set input & output format */
	csi_Para.csi_fmt.input_format = tp9950_csi_dvp_ops.info[index].input_format;
	csi_Para.csi_fmt.output_format = tp9950_csi_dvp_ops.info[index].output_format;
	csi_Para.csi_fmt.interface_mode = (INT32U)tp9950_csi_dvp_ops.info[index].interface_mode;
	csi_Para.csi_fmt.interlace_mode = (INT32U)tp9950_csi_dvp_ops.info[index].interlace_mode;
	csi_Para.csi_fmt.preview_mode = CSI_CAPTURE_MODE;
	csi_Para.csi_fmt.fieldinv = DISABLE;
	csi_Para.csi_fmt.clk_stopb = ENABLE;
	//latch_timing1
	csi_Para.csi_tim.hl_start = (INT32U)tp9950_csi_dvp_ops.info[index].hoffset;
	csi_Para.csi_tim.vl0_start = (INT32U)tp9950_csi_dvp_ops.info[index].voffset;
	csi_Para.csi_tim.vl1_start = 0x02;
	csi_Para.csi_tim.d_type = ENUM_CSI_LATCH_DELAY_3_CLOCK;
	//latch_timing2
	csi_Para.csi_tim.fget_mode = (INT32U)tp9950_csi_dvp_ops.info[index].hsync_active;
	csi_Para.csi_tim.vrst_mode = (INT32U)tp9950_csi_dvp_ops.info[index].vsync_active;
	csi_Para.csi_tim.vadd_mode = (INT32U)tp9950_csi_dvp_ops.info[index].vsync_active;
	csi_Para.csi_tim.hrst_mode = (INT32U)tp9950_csi_dvp_ops.info[index].hsync_active;
	//
	csi_Para.csi_tim.clko_inv = DISABLE;
	//csi_Para.up_scaler_mode = ENUM_CSI_DISABLE_TO_D1;

	csi_Para.h_start = csi_Para.v_start = 0x0;
	csi_Para.h_end = csi_Para.v_end = 0xfff;

	csi_Para.target_w = (INT32U)tp9950_csi_dvp_ops.info[index].target_w;
	csi_Para.target_h = (INT32U)tp9950_csi_dvp_ops.info[index].target_h;
	csi_Para.hratio = 0;		// No Scale
	csi_Para.vratio = 0;		// No Scale

	/* Set sensor's registers via SCCB */
	if(tp9950_csi_dvp_ops.info[index].target_w ==1280)
	{
       if(tp9950_sccb_write_table((regval8_t *)tp9950_720p25_dvp_init) < 0) {
            DBG_PRINT("tp9950_sccb_write_table fail!!!\r\n");
        }
        DBG_PRINT("tp9950_720p_dvp_init ok\r\n");
	}
	else
	{
       if(tp9950_sccb_write_table((regval8_t *)tp9950_1080p25_pal_dvp_init) < 0) {
            DBG_PRINT("tp9950_sccb_write_table fail!!!\r\n");
        }
        DBG_PRINT("tp9950_1080p_dvp_init ok\r\n");
	}

	DBG_PRINT("%s = %d\r\n", __func__, index);
	if(drv_l2_csi_set_fmt(TP9950_CSI_DEV,&csi_Para.csi_fmt) < 0)
	{
		DBG_PRINT("csi set fmt err!!!\r\n");
	}

	if(bufA)
	{
		drv_l2_csi_stream_on(TP9950_CSI_DEV,(gpCSIPara_t *)&csi_Para, bufA, 0);
		DBG_PRINT("Sensor tp9950 sensor dvp init completed\r\n");
	}
	else
	{
		DBG_PRINT("Input frame buffer address error, fail to start %s\r\n", tp9950_csi_dvp_ops.name);
		tp9950_csi_dvp_ops.stream_stop();
	}
	//gp_CSIDumpRegTable(TP9950_CSI_DEV);
}

/**
 * @brief   stream stop function
 * @param   none
 * @return 	none
 */
