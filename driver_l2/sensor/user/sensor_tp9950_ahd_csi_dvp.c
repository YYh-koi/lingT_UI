static INT32S tp9950_sccb_open(void)
{
#if TP9950_I2C_MODE == SENSOR_I2C_MODE_SW
	tp9950_handle = drv_l2_sccb_open_ext(&tp9950_sccb_config);
	if(tp9950_handle == 0)
	{
		DBG_PRINT("Sccb open fail.\r\n");
		return STATUS_FAIL;
	}

#elif TP99510_I2C_MODE == SENSOR_I2C_MODE_HW
	drv_l1_i2c_init(TP9950_I2C_DEVICE);
	tp9951_dvp_handle.devNumber = TP9950_I2C_DEVICE;
	tp9950_handle.slaveAddr = TP9950_ID;
	tp9950_handle.clkRate = 100;
#endif
	return STATUS_OK;
}

static void tp9950_sccb_close(void)
{
#if TP9950_I2C_MODE == SENSOR_I2C_MODE_SW
	if(tp9950_handle)
	{
		drv_l2_sccb_close(tp9950_handle);
		tp9950_handle = NULL;
	}

#elif TP9950_I2C_MODE == SENSOR_I2C_MODE_HW
	drv_l1_i2c_uninit(TP9950_I2C_DEVICE);
	tp9950_handle.devNumber = 0;
	tp9950_handle.slaveAddr = 0;
	tp9950_handle.clkRate = 0;
#endif
}

static INT32S tp9950_sccb_write(INT8U reg, INT8U value)
{
#if TP9950_I2C_MODE == SENSOR_I2C_MODE_SW
	return drv_l2_sccb_write(tp9950_handle, reg, value);

#elif TP9950_I2C_MODE == SENSOR_I2C_MODE_HW
	return drv_l1_reg_1byte_data_1byte_write(&tp9950_handle, reg, value);
#endif
}

