static INT32S GC1064_sccb_open(void)
{
#if GC1064_I2C_MODE == SENSOR_I2C_MODE_SW
	GC1064_handle = drv_l2_sccb_open_ext(&GC1064_sccb_config);
	if(GC1064_handle == 0)
	{
		DBG_PRINT("Sccb open fail.\r\n");
		return STATUS_FAIL;
	}

#elif GC1064_I2C_MODE == SENSOR_I2C_MODE_HW
	drv_l1_i2c_init(GC1064_I2C_DEVICE);
	GC1064_handle.devNumber = GC1064_I2C_DEVICE;
	GC1064_handle.slaveAddr = GC1064_ID;
	GC1064_handle.clkRate = 100;
#endif
	return STATUS_OK;
}

static void GC1064_sccb_close(void)
{
#if GC1064_I2C_MODE == SENSOR_I2C_MODE_SW
	if(GC1064_handle)
	{
		drv_l2_sccb_close(GC1064_handle);
		GC1064_handle = NULL;
	}
#elif GC1064_I2C_MODE == SENSOR_I2C_MODE_HW
	drv_l1_i2c_uninit(GC1064_I2C_DEVICE);
	GC1064_handle.slaveAddr = 0;
	GC1064_handle.clkRate = 0;
#endif
}

static INT32S GC1064_sccb_write(INT16U reg, INT8U value)
{
#if GC1064_I2C_MODE == SENSOR_I2C_MODE_SW
	return drv_l2_sccb_write(GC1064_handle, reg, value);

#elif GC1064_I2C_MODE == SENSOR_I2C_MODE_HW
	return drv_l1_reg_1byte_data_1byte_write(&GC1064_handle, reg, value);
#endif
}

static INT32S GC1064_sccb_read(INT8U reg, INT8U *value)
{
#if GC1064_I2C_MODE == SENSOR_I2C_MODE_SW
	INT16U	data;
	if(drv_l2_sccb_read(GC1064_handle, reg, &data) >= 0)
	{
		*value = (INT8U) data;
		return STATUS_OK;
	}
	else
	{
		*value = 0xFF;
		DBG_PRINT("i2C read fail!\n");
		return STATUS_FAIL;
	}

#elif GC1064_I2C_MODE == SENSOR_I2C_MODE_HW
	return drv_l1_reg_1byte_data_1byte_read(&GC1064_handle, reg, value);
#endif
}

static INT32S GC1064_sccb_write_table(regval8_t *pTable)
{
	INT32U retry_cnt = 0;

	while(1)
	{
		if(pTable->reg_num == 0xFF && pTable->value == 0xFF)
		{
			break;
		}
		//DBG_PRINT("0x%02x, 0x%02x\r\n", pTable->reg_num, pTable->value);
		if(GC1064_sccb_write(pTable->reg_num, pTable->value) < 0)
		{
			DBG_PRINT("sccb write fail.\r\n");
			retry_cnt += 1;
			if(retry_cnt >= 10)
				return STATUS_FAIL;
			continue;
		}
		else
		{
			retry_cnt = 0;
		}

		pTable++;
	}
	//DBG_PRINT("\r\n\r\n");
	return STATUS_OK;
}

static INT32S GC1064_sccb_read_table(regval8_t *pTable)
{
    INT8U Rdata;
	while(1) {
		if(pTable->reg_num == 0xFF && pTable->value == 0xFF)
			break;


		if(GC1064_sccb_read(pTable->reg_num, &Rdata) < 0) {
			DBG_PRINT("sccb read fail.\r\n");
			continue;
		}
		DBG_PRINT("0x%02x, 0x%02x\r\n", pTable->reg_num, Rdata);
		pTable++;
	}
	DBG_PRINT("\r\n\r\n");

	return STATUS_OK;
}

