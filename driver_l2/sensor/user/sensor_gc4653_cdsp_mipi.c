static INT32S GC4653_sccb_open(void)
{
#if GC4653_I2C_MODE == SENSOR_I2C_MODE_SW
	GC4653_handle = drv_l2_sccb_open_ext(&GC4653_sccb_config);
	if(GC4653_handle == 0) {
		DBG_PRINT("Sccb open fail.\r\n");
		return STATUS_FAIL;
	}
#elif GC4653_I2C_MODE == SENSOR_I2C_MODE_HW
	drv_l1_i2c_init(GC4653_I2C_DEVICE);
	GC4653_handle.devNumber = GC4653_I2C_DEVICE;
	GC4653_handle.slaveAddr = GC4653_ID;
	GC4653_handle.clkRate = 100;
#endif
	return STATUS_OK;
}

static void GC4653_sccb_close(void)
{
#if GC4653_I2C_MODE == SENSOR_I2C_MODE_SW
	if(GC4653_handle) {
		drv_l2_sccb_close(GC4653_handle);
		GC4653_handle = NULL;
	}
#elif GC4653_I2C_MODE == SENSOR_I2C_MODE_HW
	drv_l1_i2c_uninit(GC4653_I2C_DEVICE);
	GC4653_handle.slaveAddr = 0;
	GC4653_handle.clkRate = 0;
#endif
}

static INT32S GC4653_sccb_write(INT16U reg, INT8U value)
{
#if GC4653_I2C_MODE == SENSOR_I2C_MODE_SW

	return drv_l2_sccb_write(GC4653_handle, reg, value);

#elif GC4653_I2C_MODE == SENSOR_I2C_MODE_HW
	INT8U data[3];
	data[0] = (reg >> 8) & 0xFF;
	data[1] = reg & 0xFF;
	data[2] = value;
	return drv_l1_i2c_bus_write(&GC4653_handle, data, 3);
#endif
}

