static void GC4653_set_shutter(INT16U shutter)
{
	// Update Shutter
	if(shutter > 8191)
        shutter = 8191;
	if(shutter <1)
        shutter = 1;

	//Update Shutter
	GC4653_sccb_write(0x0202,(shutter>>8));
	GC4653_sccb_write(0x0203,shutter & 0xFF);
}

static int GC4653_cvt_analog_gain(int gain)
{
	INT8U i;
	INT8U total_cnt;
	INT32U tol_dig_gain = 0;

	total_cnt = sizeof(analog_gain_table) / sizeof(INT32U);

	for(i = 0; i < total_cnt; i++)
	{
		if((analog_gain_table[i] <= gain)&&(gain < analog_gain_table[i+1]))
			break;
	}

	tol_dig_gain = gain*64/analog_gain_table[i];

	GC4653_sccb_write(0x2b3, regValTable[i][0]);
	GC4653_sccb_write(0x2b4, regValTable[i][1]);

	GC4653_sccb_write(0x2b8, regValTable[i][2]);
	GC4653_sccb_write(0x2b9, regValTable[i][3]);

	GC4653_sccb_write(0x515, regValTable[i][4]);
	GC4653_sccb_write(0x519, regValTable[i][5]);
	GC4653_sccb_write(0x2d9, regValTable[i][6]);

	GC4653_sccb_write(0x20e,(tol_dig_gain>>6));
	GC4653_sccb_write(0x20f,((tol_dig_gain&0x3f)<<2));


	return 0;
}

