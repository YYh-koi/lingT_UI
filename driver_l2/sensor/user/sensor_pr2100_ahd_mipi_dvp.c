/**
 * @brief   AHD_PR2100 stream start function
 * @param   info index
 *
 * @return 	none
 */
void pr2100_cdsp_mipi_stream_on(INT32U index, INT32U bufA, INT32U bufB)
{
	INT16U		target_w, target_h, sensor_w, sensor_h;
	gpCdspFmt_t format;

//	DBG_PRINT("%s = %d\r\n", __func__, index);

	//Enabel mipi clk, set mipi clk
    if(pr2100_mipi_cfg.pixel_clk_sel == GENERATE_PIXEL_CLK)
    {
        drv_l2_mipi_ctrl_set_clk(ENABLE, 4);
        osDelay(10);
    }

    // set cdsp format
    if(MIPI_DEV_NO == MIPI_0)
    {
		format.image_source = C_CDSP_MIPI;
    }
	else
	{
		format.image_source = C_CDSP_MIPI1;
	}
	format.input_format =  pr2100_cdsp_mipi_ops.info[index].input_format;
	format.output_format = pr2100_cdsp_mipi_ops.info[index].output_format;
	target_w = pr2100_cdsp_mipi_ops.info[index].target_w;
	target_h = pr2100_cdsp_mipi_ops.info[index].target_h;
    format.hpixel = sensor_w = pr2100_cdsp_mipi_ops.info[index].sensor_w;
    format.vline = sensor_h = pr2100_cdsp_mipi_ops.info[index].sensor_h;
    format.hoffset = pr2100_cdsp_mipi_ops.info[index].hoffset;
    format.voffset = pr2100_cdsp_mipi_ops.info[index].voffset;
    format.sensor_timing_mode = pr2100_cdsp_mipi_ops.info[index].interface_mode;
    format.sensor_hsync_mode = pr2100_cdsp_mipi_ops.info[index].hsync_active;
    format.sensor_vsync_mode = pr2100_cdsp_mipi_ops.info[index].vsync_active;
    DBG_PRINT("cdsp set normal mode!!!\r\n");

    if(drv_l2_cdsp_set_fmt(&format, 0) < 0)
	{
		DBG_PRINT("cdsp set fmt err!!!\r\n");
	}

    drv_l1_CdspSetDataSource(SDRAM_INPUT);
 /*
	// set scale down
	if((format.hpixel > target_w) || (format.vline > target_h))
	{
		drv_l2_cdsp_set_yuv_scale(target_w, target_h);
	}
*/
	// cdsp start
	drv_l2_cdsp_stream_on(0, bufA, bufB, 0);

    //mipi start
	if(drv_l1_mipi_set_parameter(MIPI_DEV_NO, &pr2100_mipi_cfg) < 0)
	{
		DBG_PRINT("MIPI0 init fail !!!\r\n");
	}

	drv_l1_CdspSetDataSource(MIPI_INPUT);
	DBG_PRINT(" cdsp mipi init done!!\r\n");

  // while(1);
}

void pr2100_csi_dvp_stream_start(INT32U index, INT32U bufA, INT32U bufB)
{
	gpCSIPara_t csi_Para;

	gp_memset((INT8S *)&csi_Para, 0, sizeof(gpCSIPara_t));

	/* set input & output format */
	csi_Para.csi_fmt.input_format = pr2100_csi_dvp_ops.info[index].input_format;
	csi_Para.csi_fmt.output_format = pr2100_csi_dvp_ops.info[index].output_format;

	csi_Para.csi_tim.clki_inv = 1;
    csi_Para.csi_fmt.interface_mode = pr2100_csi_dvp_ops.info[index].interface_mode;
    csi_Para.csi_fmt.preview_mode = CSI_CAPTURE_MODE;
	csi_Para.csi_fmt.clk_stopb = ENABLE;
	csi_Para.csi_tim.fget_mode = ENUM_CSI_RISING_EDGE;
    csi_Para.csi_tim.hrst_mode = ENUM_CSI_RISING_EDGE;
    csi_Para.csi_tim.vadd_mode = ENUM_CSI_RISING_EDGE;
    csi_Para.csi_tim.vrst_mode = ENUM_CSI_RISING_EDGE;
    csi_Para.csi_tim.d_type = ENUM_CSI_LATCH_DELAY_3_CLOCK;
    csi_Para.h_start = 0x0;
    csi_Para.v_start = 0x0;
    csi_Para.h_end = csi_Para.v_end = 0xfff;

	csi_Para.target_w = pr2100_csi_dvp_ops.info[index].target_w;
	csi_Para.target_h = pr2100_csi_dvp_ops.info[index].target_h;
	csi_Para.hratio = 0;		// No Scale
	csi_Para.vratio = 0;		// No Scale

	DBG_PRINT("%s = %d\r\n", __func__, index);
    if(drv_l2_csi_set_fmt(PR2100_CSI_DEV,&csi_Para.csi_fmt) < 0)
    {
		DBG_PRINT("csi set fmt err!!!\r\n");
	}

	// init sensor
	pr2100_sccb_write_table((regval8_t *)PR2100_init_table);

	if(bufA) {
		drv_l2_csi_stream_on(PR2100_CSI_DEV,(gpCSIPara_t *)&csi_Para, bufA, bufB);
	} else {
		DBG_PRINT("Input frame buffer address error, fail to start %s\r\n", pr2100_csi_dvp_ops.name);
		pr2100_csi_dvp_ops.stream_stop();
	}
	DBG_PRINT("Sensor pr2100 sensor dvp init completed\r\n");

  // while(1);
}

