static INT32S pr2100_sccb_open(void)
{
#if PR2100_I2C_MODE == SENSOR_I2C_MODE_SW
	pr2100_handle = drv_l2_sccb_open_ext(&pr2100_sccb_config);
	if(pr2100_handle == 0)
	{
		DBG_PRINT("Sccb open fail.\r\n");
		return STATUS_FAIL;
	}
#elif PR2100_I2C_MODE == SENSOR_I2C_MODE_HW
	drv_l1_i2c_init(PR2100_I2C_DEVICE);
	pr2100_handle.devNumber = PR2100_I2C_DEVICE;
	pr2100_handle.slaveAddr = PR2100_ID;
	pr2100_handle.clkRate = 100;
#endif
	return STATUS_OK;
}

static void pr2100_sccb_close(void)
{
#if PR2100_I2C_MODE == SENSOR_I2C_MODE_SW
	if(pr2100_handle)
	{
		drv_l2_sccb_close(pr2100_handle);
		pr2100_handle = NULL;
	}

#elif PR2100_I2C_MODE == SENSOR_I2C_MODE_HW
	drv_l1_i2c_uninit(PR2100_I2C_DEVICE);
	pr2100_handle.slaveAddr = 0;
	pr2100_handle.clkRate = 0;
#endif
}

static INT32S pr2100_sccb_write(INT16U reg, INT8U value)
{
#if PR2100_I2C_MODE == SENSOR_I2C_MODE_SW
	return drv_l2_sccb_write(pr2100_handle, reg, value);

#elif PR2100_I2C_MODE == SENSOR_I2C_MODE_HW
	return drv_l1_reg_1byte_data_1byte_write(&pr2100_handle, reg, value);
#endif
}


static INT32S pr2100_sccb_read(INT16U reg,INT16U *value)
{
#if PR2100_I2C_MODE == SENSOR_I2C_MODE_SW
	INT16U	data;

	if(drv_l2_sccb_read(pr2100_handle, reg, &data) >= 0)
	{
		*value = (INT16U) data;
		//DBG_PRINT("0x%02x, 0x%02x\r\n", reg, *value);
		return STATUS_OK;
	}
	else
	{
		*value = 0xFF;
		//DBG_PRINT("0x%02x, 0x%02x\r\n", reg, *value);
		return STATUS_FAIL;
	}

#elif PR2100_I2C_MODE == SENSOR_I2C_MODE_HW
	INT8U	value = 0;
	if(drv_l1_reg_1byte_data_1byte_read(&pr2100_handle, reg, &value) >= 0)
	{
		DBG_PRINT("0x%02x, 0x%02x\r\n", reg, value);
		return STATUS_OK;
	}
	else
	{
		DBG_PRINT("sccb_read fail...\r\n");
		return STATUS_FAIL;
	}

#endif
}

