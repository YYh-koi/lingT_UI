static int IMX230_set_xfps_exposure_time(sensor_exposure_t *si)
{
    int idx,iso_x;

    iso_x = (drv_l2_CdspGetIso() & 0xF);
	if (iso_x <= 0)
		iso_x = 1;

    si->sensor_ev_idx += si->ae_ev_step;
    if(si->sensor_ev_idx >= si->max_ev_idx)
    	si->sensor_ev_idx = si->max_ev_idx;
    if(si->sensor_ev_idx < 0)
    	si->sensor_ev_idx = 0;

    idx = si->sensor_ev_idx * 3;
    si ->time = p_expTime_table[idx];
    si ->analog_gain = (int)(p_expTime_table[idx+1]*iso_x);
    si ->digital_gain = p_expTime_table[idx+2];;

    //DBG_PRINT("[EV=%d, offset=%d]: time = %d, analog gain =0x%x, iso_x=%d\r\n", si->sensor_ev_idx, si->ae_ev_step, si->time, si->analog_gain, iso_x);
    //crf
    // exposure time
    if(si ->time != pre_sensor_time)
    {
        pre_sensor_time = si->time;// = 840*2;
        IMX230_set_shutter(pre_sensor_time);
       // DBG_PRINT("IMX230_set_xfps_exposure_time: time = %d!!!\r\n", si->time);

    }

    //gain
    if(si ->analog_gain != pre_sensor_a_gain)
    {
        // gain
        pre_sensor_a_gain = si->analog_gain;// = 64*1.36*1.3;//92;
        IMX230_cvt_analog_gain(pre_sensor_a_gain);
       // DBG_PRINT("IMX230_set_xfps_exposure_time: analog_gain = %d!!!\r\n", si->analog_gain);
    }

    return 0;
}

