void gc2145_csi_mipi_init(void)
{
	gc2145_sccb_open();

	// Reset
	gpio_set_port_attribute(GC2145_RESET, ATTRIBUTE_HIGH);
	gpio_init_io(GC2145_RESET, GPIO_OUTPUT);
	gpio_write_io(GC2145_RESET, DATA_HIGH);
    osDelay(10);
    gpio_write_io(GC2145_RESET, DATA_LOW);
    osDelay(10);
    gpio_write_io(GC2145_RESET, DATA_HIGH);
    osDelay(10);

#if CSI_ENABLE
	drv_l1_csi_init(GC2145_CSI_DEV);
#endif
	drv_l1_mipi_init(MIPI_DEV_NO,ENABLE, 0);
#if CSI_ENABLE
	drv_l2_sensor_set_csi_source(SENSOR_INTERFACE_MIPI, GC2145_CSI_DEV, MIPI_DEV_NO);

	DBG_PRINT("Sensor GC2145 csi(%d) mipi(%d) init completed\r\n", GC2145_CSI_DEV, MIPI_DEV_NO);
#else
	DBG_PRINT("Sensor GC2145 mipi(%d) init completed\r\n", MIPI_DEV_NO);
#endif

}

/**
 * @brief   un-initialization function
 * @param   sensor format parameters
 * @return 	none
 */
void gc2145_csi_mipi_uninit(void)
{
	// disable mclk
	drv_l2_sensor_set_mclkout(MCLK_NONE, GC2145_CSI_DEV);

#if CSI_ENABLE
	// csi disable
    drv_l2_csi_stop(GC2145_CSI_DEV);
#endif
	// mipi disable
    drv_l1_mipi_init(MIPI_DEV_NO, DISABLE, 0);

	// release sccb
	gc2145_sccb_close();

#if CSI_ENABLE
	// CSI uninit
    drv_l1_csi_uninit(GC2145_CSI_DEV);
#endif
}

/**
 * @brief   stream start function
 * @param   info index
 *
 * @return 	none
 */
void gc2145_csi_mipi_stream_on(INT32U index, INT32U bufA, INT32U bufB)
{
	gpCSIPara_t csi_Para;

	// set sensor size
	DBG_PRINT("%s = %d\r\n", __func__, index);

    if(gc2145_mipi_cfg.pixel_clk_sel == GENERATE_PIXEL_CLK)
    {
        drv_l2_mipi_ctrl_set_clk(ENABLE, 4);
    	vTaskDelay(200);
	}

#if CSI_ENABLE
	gp_memset((INT8S *)&csi_Para, 0, sizeof(gpCSIPara_t));
	/* set input & output format */

    csi_Para.csi_fmt.input_format = CSI_IN_YUYV;

	if(gc2145_csi_mipi_ops.info[index].output_format == V4L2_PIX_FMT_GP420) {
        csi_Para.csi_fmt.output_format = CSI_OUT_GP420;
	} else
        csi_Para.csi_fmt.output_format = CSI_OUT_YUYV;
    csi_Para.csi_fmt.fifo_size = 0;
    csi_Para.csi_fmt.interface_mode = CSI_HREF;
    csi_Para.csi_fmt.preview_mode = CSI_CAPTURE_MODE;
    csi_Para.csi_fmt.clk_stopb = ENABLE;//
    csi_Para.csi_tim.hrst_mode = ENUM_CSI_RISING_EDGE;
    csi_Para.csi_tim.vadd_mode = ENUM_CSI_RISING_EDGE;
    csi_Para.csi_tim.vrst_mode = ENUM_CSI_RISING_EDGE;
    csi_Para.csi_tim.d_type = DELAY_1CLOCK;
    csi_Para.h_start = csi_Para.v_start = 0x0;
    csi_Para.h_end = csi_Para.v_end = 0xfff;

	switch(index)
	{
	case 0:
		csi_Para.target_w = gc2145_csi_mipi_ops.info[index].target_w;
		csi_Para.target_h = gc2145_csi_mipi_ops.info[index].target_h;
		csi_Para.hratio = 0;		// No Scale
		csi_Para.vratio = 0;		// No Scale
		break;

	case 1:
		break;

	case 2:
		break;

	case 3:
		break;

	default:
		while(1);
	}

    osDelay(30);

	if(drv_l2_csi_set_fmt(GC2145_CSI_DEV, &csi_Para.csi_fmt) < 0)
    {
		DBG_PRINT("csi set fmt err!!!\r\n");
	}
#endif
	// set mipi format.
	gc2145_mipi_cfg.h_size = gc2145_csi_mipi_ops.info[index].sensor_w;//format.hpixel;
	gc2145_mipi_cfg.v_size = gc2145_csi_mipi_ops.info[index].sensor_h;//format.vline;

	//mipi start
    drv_l1_mipi_set_parameter(MIPI_DEV_NO, &gc2145_mipi_cfg);
#if MIPI_ISR_TEST == 1
    drv_l1_mipi_isr_register(mipi_gc2145_handle);
    drv_l1_mipi_set_irq_enable(MIPI_DEV_NO, ENABLE, MIPI_SOF);
#endif

#if CSI_ENABLE
	if(bufA) {
		drv_l2_csi_stream_on(GC2145_CSI_DEV, (gpCSIPara_t *)&csi_Para, bufA, bufB);
	} else {
		DBG_PRINT("Input frame buffer address error, fail to start %s\r\n", gc2145_csi_mipi_ops.name);
		gc2145_csi_mipi_ops.stream_stop();
	}
#endif

	// init sensor
    gc2145_sccb_write_table((regval8_t *)gc2145_reset_table);
    osDelay(200);
    gc2145_sccb_write_table((regval8_t *)GC2145_init_table);
	gc2145_sccb_write_table((regval8_t *)GC2145_resolution_table);

	//DBG_PRINT("mipi chk fail cnt %d\r\n",drv_l1_mipi_check_header(MIPI_0, 0x110a001e ,1000));//check header

	DBG_PRINT(" ~~gc2145_csi_mipi_stream_on done!!\r\n");
}

