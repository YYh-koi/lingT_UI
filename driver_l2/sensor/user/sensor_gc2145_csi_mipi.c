INT32S gc2145_sccb_open(void)
{
#if GC2145_I2C_MODE == SENSOR_I2C_MODE_SW
#if 0
	gc2145_handle = drv_l2_sccb_open(GC2145_ID, 8, 8);
	if(gc2145_handle == 0) {
		DBG_PRINT("Sccb open fail.\r\n");
		return STATUS_FAIL;
	}
#else
	sccb_config_t cfg;

	cfg.scl_port = 	IO_B4;
	cfg.scl_drv =  	IOD_DRV_16mA;
	cfg.sda_port = 	IO_B5;
	cfg.sda_drv =  	IOD_DRV_16mA;
	cfg.pwdn_port = 0;
	cfg.pwdn_drv =  0;
	cfg.have_pwdn = 0;
	cfg.RegBits =   8;
	cfg.DataBits =  8;
	cfg.slaveAddr =	GC2145_ID;
	cfg.timeout =	0x20000;
	cfg.clock_rate =100;

	gc2145_handle = drv_l2_sccb_open_ext(&cfg);

	if(gc2145_handle == 0) {
		DBG_PRINT("Sccb open fail.\r\n");
		return STATUS_FAIL;
	}
#endif
#elif GC2145_I2C_MODE == SENSOR_I2C_MODE_HW
	drv_l1_i2c_init(GC2145_I2C_DEVICE);
	gc2145_handle.devNumber = GC2145_I2C_DEVICE;
	gc2145_handle.slaveAddr = GC2145_ID;
	gc2145_handle.clkRate = 100;
#endif
	return STATUS_OK;
}

void gc2145_sccb_close(void)
{
#if GC2145_I2C_MODE == SENSOR_I2C_MODE_SW
	if(gc2145_handle) {
		drv_l2_sccb_close(gc2145_handle);
		gc2145_handle = NULL;
	}
#elif GC2145_I2C_MODE == SENSOR_I2C_MODE_HW
	drv_l1_i2c_uninit(GC2145_I2C_DEVICE);
	gc2145_handle.slaveAddr = 0;
	gc2145_handle.clkRate = 0;
#endif
}

INT32S gc2145_sccb_write(INT16U reg, INT8U value)
{
#if GC2145_I2C_MODE == SENSOR_I2C_MODE_SW
	return drv_l2_sccb_write(gc2145_handle, reg, value);

#elif GC2145_I2C_MODE == SENSOR_I2C_MODE_HW
	INT8U data[3];

	data[0] = (reg >> 8) & 0xFF;
	data[1] = reg & 0xFF;
	data[2] = value;
	return drv_l1_i2c_bus_write(&gc2145_handle, data, 3);
#endif
}

INT32S gc2145_sccb_write_table(regval8_t *pTable)
{
	while(1) {
		if(pTable->reg_num == 0xFF && pTable->value == 0xFF) {
			break;
		}

		//DBG_PRINT("0x%02x, 0x%02x\r\n", pTable->reg_num, pTable->value);
		if(gc2145_sccb_write(pTable->reg_num, pTable->value) < 0) {
			DBG_PRINT("sccb write fail.\r\n");
			continue;
		}
		pTable++;
	}
	return STATUS_OK;
}

