static INT32S gc1054_sccb_open(void)
{
#if GC1054_I2C_MODE == SENSOR_I2C_MODE_SW
	gc1054_handle = drv_l2_sccb_open_ext(&gc1054_sccb_config);
	if(gc1054_handle == 0)
	{
		DBG_PRINT("Sccb open fail.\r\n");
		return STATUS_FAIL;
	}

#elif GC1054_I2C_MODE == SENSOR_I2C_MODE_HW
	drv_l1_i2c_init(GC1054_I2C_DEVICE);
	gc1054_handle.devNumber = GC1054_I2C_DEVICE;
	gc1054_handle.slaveAddr = GC1054_ID;
	gc1054_handle.clkRate = 150;
#endif
	return STATUS_OK;
}

static void gc1054_sccb_close(void)
{
#if GC1054_I2C_MODE == SENSOR_I2C_MODE_SW
	if(gc1054_handle)
	{
		drv_l2_sccb_close(gc1054_handle);
		gc1054_handle = NULL;
	}
#elif GC1054_I2C_MODE == SENSOR_I2C_MODE_HW
	drv_l1_i2c_uninit(GC1054_I2C_DEVICE);
	gc1054_handle.slaveAddr = 0;
	gc1054_handle.clkRate = 0;
#endif
}

static INT32S gc1054_sccb_write(INT16U reg, INT8U value)
{
#if GC1054_I2C_MODE == SENSOR_I2C_MODE_SW
	return drv_l2_sccb_write(gc1054_handle, reg, value);

#elif GC1054_I2C_MODE == SENSOR_I2C_MODE_HW
	return drv_l1_reg_1byte_data_1byte_write(&gc1054_handle, reg, value);
#endif
}

static INT32S gc1054_sccb_read(INT8U reg, INT8U *value)
{
#if GC1054_I2C_MODE == SENSOR_I2C_MODE_SW
	INT16U	data;
	if(drv_l2_sccb_read(gc1054_handle, reg, &data) >= 0)
	{
		*value = (INT8U) data;
		return STATUS_OK;
	}
	else
	{
		*value = 0xFF;
		DBG_PRINT("i2C read fail!\n");
		return STATUS_FAIL;
	}

#elif GC1054_I2C_MODE == SENSOR_I2C_MODE_HW
	return drv_l1_reg_1byte_data_1byte_read(&gc1054_handle, reg, value);
#endif
}

static INT32S gc1054_sccb_write_table(regval8_t *pTable)
{
	INT32U retry_cnt = 0;

	while(1)
	{
		if(pTable->reg_num == 0xFF && pTable->value == 0xFF)
		{
			break;
		}
		//DBG_PRINT("0x%02x, 0x%02x\r\n", pTable->reg_num, pTable->value);
		if(gc1054_sccb_write(pTable->reg_num, pTable->value) < 0)
		{
			DBG_PRINT("sccb write fail.\r\n");
			retry_cnt += 1;
			if(retry_cnt >= 10)
				return STATUS_FAIL;
			continue;
		}
		else
		{
			retry_cnt = 0;
		}

		pTable++;
	}
	//DBG_PRINT("\r\n\r\n");
	return STATUS_OK;
}

static INT32S gc1054_sccb_read_table(regval8_t *pTable)
{
    INT8U Rdata;
	while(1) {
		if(pTable->reg_num == 0xFF && pTable->value == 0xFF)
			break;


		if(gc1054_sccb_read(pTable->reg_num, &Rdata) < 0) {
			DBG_PRINT("sccb read fail.\r\n");
			continue;
		}
		DBG_PRINT("0x%02x, 0x%02x\r\n", pTable->reg_num, Rdata);
		pTable++;
	}
	DBG_PRINT("\r\n\r\n");

	return STATUS_OK;
}

