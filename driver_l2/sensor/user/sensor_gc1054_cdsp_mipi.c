static int gc1054_cvt_agc_gain(int analog_gain)
{
	INT32U Analog_Multiple[11]={1000, 1420, 1990, 2850, 4030,5770,8060,11530,16120,23300,32570};

	INT32U Analog_Index;
	INT32U Digital_Gain;
	INT32U Decimal;
	INT32U gc1054_analog_gain=0;
	INT32S ret = 0;

	gc1054_analog_gain = analog_gain*10;
	Analog_Index=0;

	while(Analog_Index<11)
	{
	  if(gc1054_analog_gain<Analog_Multiple[Analog_Index])
	  {
		break;
	  }
	  else
	  {
		Analog_Index++;
	  }
	}

	Digital_Gain = gc1054_analog_gain*1000/Analog_Multiple[Analog_Index-1];
	Decimal=(Digital_Gain*64)/1000;

    ret = gc1054_sccb_write(0xfe, 0x01);
	if(ret < 0)
		return ret;
  	ret = gc1054_sccb_write(0xb1, Decimal >> 6);
	if(ret < 0)
		return ret;
	ret = gc1054_sccb_write(0xb2, (Decimal << 2) & 0xfc);
	if(ret < 0)
		return ret;
	ret = gc1054_sccb_write(0xb6, Analog_Index - 1);
	if(ret < 0)
		return ret;
	ret = gc1054_sccb_write(0xfe, 0x00);
	if(ret < 0)
		return ret;
	//DBG_PRINT("[analog gain =0x%x, b1=%d, b2=%d, b6=%d\r\n",gc1054_analog_gain, (Decimal >> 6),((Decimal << 2) & 0xfc),(Analog_Index - 1));
}

static int gc1054_set_xfps_exposure_time(sensor_exposure_t *si)
{
	unsigned char	t1, t2;
	int				idx, temp, ret;
	INT8U 			iso_x = 1;

	//DBG_PRINT("%s:%d\n", __FUNCTION__, __LINE__);
    iso_x = (drv_l2_CdspGetIso() & 0xF);
	if (iso_x <= 0)
		iso_x = 1;

	si->sensor_ev_idx += si->ae_ev_step;
	if(si->sensor_ev_idx >= si->max_ev_idx)
		si->sensor_ev_idx = si->max_ev_idx;
	if(si->sensor_ev_idx < 0)
		si->sensor_ev_idx = 0;

	idx = si->sensor_ev_idx * 3;

	si->time = p_expTime_table[idx];
	si->analog_gain = (p_expTime_table[idx + 1] * iso_x);
    si->digital_gain = p_expTime_table[idx+2];


#if 0						//ae debug
	DBG_PRINT("[EV=%d, offset=%d]: time = %d, analog gain =0x%x\r\n", si->sensor_ev_idx, si->ae_ev_step, si->time, si->analog_gain);
#endif
#if 0	//ae debug
	DBG_PRINT("[EV=%d\r\n", si->sensor_ev_idx);
#endif

	// exposure time
	if(si->time != pre_sensor_time)
	{
		pre_sensor_time = si->time;
		temp = si->time;

		t1 = (temp & 0xff);
		t2 = (temp >> 8) & 0x00ff;

		ret = gc1054_sccb_write(0x04, t1);
		if(ret < 0)
			return ret;
		ret = gc1054_sccb_write(0x03, t2);
		if(ret < 0)
		{
			DBG_PRINT("ERR: write sensor time = 0x%x!!!\r\n", temp);
			return ret;
		}
	}

	//gain
	if(si->analog_gain != pre_sensor_a_gain)
	{
		// gain
		pre_sensor_a_gain = si->analog_gain;

		temp = si->analog_gain;
		ret = gc1054_cvt_agc_gain(temp);
		if(ret < 0)
		{
			DBG_PRINT("ERR: write sensor analog agin = 0x%x!!!\r\n", temp);
			return ret;
		}
	}

	return 0;
}


