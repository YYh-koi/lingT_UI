static INT32S gc2083_sccb_write_table(regval16_t *pTable)
{
    INT32U retry_cnt=0;

	while(1)
	{
		if (pTable->reg_num == 0 && pTable->value == 0)
		{
			break;
		}

		//	DBG_PRINT("0x%04x, 0x%02x\r\n", pTable->reg_num, pTable->value);

		if(gc2083_sccb_write(pTable->reg_num, pTable->value) < 0) {
			DBG_PRINT("%s: sccb write fail: reg = 0x%x, val = 0x%x\r\n", __FUNCTION__, pTable->reg_num, pTable->value);
			retry_cnt += 1;
			if(retry_cnt >= 10){
                retry_cnt = 0;
				return STATUS_FAIL;
			}
			continue;
		}
		else{
            #if READ_SCCB
            INT8U data = 0;
            osDelay(5);
            if(gc2083_sccb_read(pTable->reg_num, (INT16U *)&data) == STATUS_OK){
                DBG_PRINT("sensor i2c reg[0x%04x] = 0x%04x, read = 0x%04x\r\n", pTable->reg_num, data);
            }
            else{
                DBG_PRINT("sensor i2c reg[0x%04x] = 0x%04x, read fail\r\n", pTable->reg_num);
            }
            #endif
		}

		pTable++;
	}

	return STATUS_OK;
}

