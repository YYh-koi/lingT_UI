static INT32S gc2083_sccb_open(void)
{
#if GC2083_I2C_MODE == SENSOR_I2C_MODE_SW
	gc2083_handle = drv_l2_sccb_open_ext(&gc2083_sccb_config);
	if(gc2083_handle == 0)
	{
		DBG_PRINT("Sccb open fail.\r\n");
		return STATUS_FAIL;
	}
#elif GC2083_I2C_MODE == SENSOR_I2C_MODE_HW
	drv_l1_i2c_init(GC2083_I2C_DEVICE);
	gc2083_handle.devNumber = GC2083_I2C_DEVICE;
	gc2083_handle.slaveAddr = gc2083_ID;
	gc2083_handle.clkRate = SCL_RATE;
#endif
	return STATUS_OK;
}

static void gc2083_sccb_close(void)
{
#if GC2083_I2C_MODE == SENSOR_I2C_MODE_SW
	if(gc2083_handle)
	{
		drv_l2_sccb_close(gc2083_handle);
		gc2083_handle = NULL;
	}
#elif GC2083_I2C_MODE == SENSOR_I2C_MODE_HW
	drv_l1_i2c_uninit(GC2083_I2C_DEVICE);
	gc2083_handle.slaveAddr = 0;
	gc2083_handle.clkRate = 0;
#endif
}

