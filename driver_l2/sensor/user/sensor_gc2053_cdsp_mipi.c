static int gc2053_cvt_analog_gain(int gain)
{
	INT16U i;
	INT16U total_cnt;
	INT32U Digital_Gain = 0;

	total_cnt = sizeof(GainLevelTable) / sizeof(INT32U);
	for(i = 0; i < total_cnt; i++)
	{
		if((GainLevelTable[i] <= gain)&&(gain < GainLevelTable[i+1]))
			break;
	}
	gc2053_sccb_write(0xfe,0x00);
	//gc2053_sccb_write(0x87,0x58);

	gc2053_sccb_write(0xb4,RegValTable[i][0]);
	gc2053_sccb_write(0xb3,RegValTable[i][1]);
    gc2053_sccb_write(0xb8,RegValTable[i][2]);
	gc2053_sccb_write(0xb9,RegValTable[i][3]);
	Digital_Gain = gain*64/GainLevelTable[i];
	//DBG_PRINT("In Gain =%d, GainLevel = %d, RegVal = 0x%x, 0x%x, 0x%x, 0x%x, Dgain = %d\r\n", gain, GainLevelTable[i], RegValTable[i][0], RegValTable[i][1], RegValTable[i][2], RegValTable[i][3], Digital_Gain);
	gc2053_sccb_write(0xb1,(Digital_Gain>>6));
	gc2053_sccb_write(0xb2,((Digital_Gain&0x3f)<<2));
	//gc2053_sccb_write(0xbf,0x00);
	//gc2053_sccb_write(0x87,0x18);

    return 0;
}


