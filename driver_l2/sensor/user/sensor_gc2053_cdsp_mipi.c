static INT32S gc2053_sccb_open(void)
{
	DBG_PRINT("%s\r\n", __FUNCTION__);
#if GC2053_I2C_MODE == SENSOR_I2C_MODE_SW
	gc2053_handle = drv_l2_sccb_open_ext(&gc2053_sccb_config);
	if(gc2053_handle == 0)
	{
		DBG_PRINT("Sccb open fail.\r\n");
		return STATUS_FAIL;
	}
#elif GC2053_I2C_MODE == SENSOR_I2C_MODE_HW
	drv_l1_i2c_init(GC2053_I2C_DEVICE);
	gc2053_handle.devNumber = GC2053_I2C_DEVICE;
	gc2053_handle.slaveAddr = gc2053_ID;
	gc2053_handle.clkRate = 200;
#endif
	return STATUS_OK;
}

static void gc2053_sccb_close(void)
{
#if GC2053_I2C_MODE == SENSOR_I2C_MODE_SW
	if(gc2053_handle)
	{
		drv_l2_sccb_close(gc2053_handle);
		gc2053_handle = NULL;
	}
#elif GC2053_I2C_MODE == SENSOR_I2C_MODE_HW
	drv_l1_i2c_uninit(GC2053_I2C_DEVICE);
	gc2053_handle.slaveAddr = 0;
	gc2053_handle.clkRate = 0;
#endif
}

static INT32S gc2053_sccb_write(INT8U reg, INT8U value)
{
#if GC2053_I2C_MODE == SENSOR_I2C_MODE_SW
	return drv_l2_sccb_write(gc2053_handle, reg, value);

#elif GC2053_I2C_MODE == SENSOR_I2C_MODE_HW
	return drv_l1_reg_1byte_data_1byte_write(&gc2053_handle, reg, value);
#endif
}


