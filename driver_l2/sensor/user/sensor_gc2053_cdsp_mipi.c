/**
 * @brief   stream start function
 * @param   info index
 *
 * @return 	none
 */
void gc2053_cdsp_mipi_stream_on(INT32U index, INT32U bufA, INT32U bufB)
{
	INT16U target_w, target_h, sensor_w, sensor_h;
	gpCdspFmt_t format;
    INT32U sensor_id = 0;
    INT8U docropflag = 0;

 	// set sensor size
	DBG_PRINT("%s = %d\r\n", __func__, index);

	g_sensor_info_idx =index;

    if(gc2053_mipi_cfg.pixel_clk_sel == GENERATE_PIXEL_CLK)
    {
        drv_l2_mipi_ctrl_set_clk(ENABLE, 3);
        osDelay(10);
    }

    // set cdsp format
    if(MIPI_DEV_NO == MIPI_0)
    {
		format.image_source = C_CDSP_MIPI;
    }
	else
	{
		format.image_source = C_CDSP_MIPI1;
	}
	format.input_format =  gc2053_cdsp_mipi_ops.info[index].input_format;
	format.output_format = gc2053_cdsp_mipi_ops.info[index].output_format;
	target_w = gc2053_cdsp_mipi_ops.info[index].target_w;
	target_h = gc2053_cdsp_mipi_ops.info[index].target_h;
	if((format.image_source == C_CDSP_BINMODE)||(format.image_source == C_CDSP_BINMODE1))
	{
		//use binmode input, cdsp use target size, sensor size would larger than target size,
		//binmode use by2, by4, crop, to scale down input, so dont need cdsp scale size here
		format.hpixel = sensor_w = gc2053_cdsp_mipi_ops.info[index].target_w;
		format.vline = sensor_h = gc2053_cdsp_mipi_ops.info[index].target_h;
		DBG_PRINT("cdsp set binmode!!!\r\n");
	}
	else if((format.image_source == C_CDSP_BINMODE_MIPI)||(format.image_source == C_CDSP_BINMODE_MIPI1))
    {
        format.hpixel = gc2053_cdsp_mipi_ops.info[index].target_w;
        format.vline = gc2053_cdsp_mipi_ops.info[index].target_h;
        format.h_input = sensor_w = gc2053_cdsp_mipi_ops.info[index].sensor_w;
        format.v_input = sensor_h = gc2053_cdsp_mipi_ops.info[index].sensor_h;

        format.hoffset = gc2053_cdsp_mipi_ops.info[index].hoffset;
		format.voffset = gc2053_cdsp_mipi_ops.info[index].voffset;
		format.sensor_timing_mode = gc2053_cdsp_mipi_ops.info[index].interface_mode;
		format.sensor_hsync_mode = gc2053_cdsp_mipi_ops.info[index].hsync_active;
		format.sensor_vsync_mode = gc2053_cdsp_mipi_ops.info[index].vsync_active;
		DBG_PRINT("cdsp set binmode mipi!!!\r\n");
    }
    else
    {
		format.hpixel = sensor_w = gc2053_cdsp_mipi_ops.info[index].sensor_w;
		format.vline = sensor_h = gc2053_cdsp_mipi_ops.info[index].sensor_h;
		format.hoffset = gc2053_cdsp_mipi_ops.info[index].hoffset;
		format.voffset = gc2053_cdsp_mipi_ops.info[index].voffset;
		format.sensor_timing_mode = gc2053_cdsp_mipi_ops.info[index].interface_mode;
		format.sensor_hsync_mode = gc2053_cdsp_mipi_ops.info[index].hsync_active;
		format.sensor_vsync_mode = gc2053_cdsp_mipi_ops.info[index].vsync_active;
		DBG_PRINT("cdsp set normal mode!!!\r\n");
    }

    if(drv_l2_cdsp_set_fmt(&format, num_sensors) < 0)
	{
		DBG_PRINT("cdsp set fmt err!!!\r\n");
	}

    drv_l1_CdspSetDataSource(SDRAM_INPUT);

	// set scale down
	if(((sensor_w > target_w) || (sensor_h > target_h)) && (docropflag == 0))
	{
		drv_l2_cdsp_set_yuv_scale(target_w, target_h);
	}
	else if(((sensor_w > target_w) || (sensor_h > target_h)) && (docropflag == 1))
	{
        INT32U point_x = 16, point_y = 16;
		drv_l1_CdspSetCrop(point_x, point_y, target_w, target_h);
		drv_l1_CdspSetCropEn(docropflag);	//1:Enable, 0:Disable
	}

	// cdsp start
	drv_l2_CdspTableRegister((gpCisCali_t*)&g_cali, sensor_id);
	drv_l2_cdsp_stream_on(ENABLE, bufA, bufB, num_sensors);
	drv_l2_cdsp_analog_gain_thr_init(GainThrTable);
    drv_l2_cdsp_enable((gpUserFav_t *)&g_FavTable, sensor_w, sensor_h, target_w, target_h, sensor_id);

	//mipi start
	if(drv_l1_mipi_set_parameter(MIPI_DEV_NO, &gc2053_mipi_cfg) < 0)
	{
		DBG_PRINT("MIPI%d init fail !!!\r\n", MIPI_DEV_NO);
	}

	#if MIPI_ISR_TEST == 1
	if (MIPI_DEV_NO == MIPI_1)
	{
		drv_l1_mipi_B_isr_register(&mipi_gc2053_handle);
		drv_l1_mipi_set_irq_enable(MIPI_1, ENABLE, MIPI_SOF);
	}
	else
	{
		drv_l1_mipi_isr_register(&mipi_gc2053_handle);
		drv_l1_mipi_set_irq_enable(MIPI_0, ENABLE, MIPI_SOF);
	}

	#endif

	// init sensor
	if(gc2053_cdsp_mipi_ops.info[index].sensor_fps == 30)
	{
		gc2053_sccb_write_table((regval16_t *)gc2053_Mipi_Raw10_1080P_30fps);
		//DBG_PRINT("Sensor GC2053 30fps init completed\r\n");
	}
	else if(gc2053_cdsp_mipi_ops.info[index].sensor_fps == 25)
	{
		#if MIPI_LANE_NO == MIPI_2_LANE
		gc2053_sccb_write_table((regval16_t *)gc2053_Mipi_Raw10_1080P_25fps_2lane);
		DBG_PRINT("Sensor GC2053 2LANE 25fps init completed\r\n");
		#else
		gc2053_sccb_write_table((regval16_t *)gc2053_Mipi_Raw10_1080P_25fps);
		//DBG_PRINT("Sensor GC2053 25fps init completed\r\n");
		#endif
	}

	// reset sensor ev idx
	seInfo.ae_ev_step = 0;
	drv_l1_CdspSetWbGain(0x53, 0x40, 0x88);
	gc2053_set_xfps_exposure_time(&seInfo);
	//DBG_PRINT("gc2053 mipi Exposure Time set!!\r\n");

	drv_l1_CdspSetDataSource(MIPI_INPUT);
	//DBG_PRINT("gc2053 cdsp mipi init done!!\r\n");

	DBG_PRINT("gc2053 cdsp mipi init done!!\r\n");

}

