/**
 * @brief   stream start function
 * @param   info index
 *
 * @return 	none
 */
void imx307_cdsp_mipi_stream_on(INT32U index, INT32U bufA, INT32U bufB, INT8U fifo_size)
{
    INT8U docropflag = 0;
    INT16U target_w, target_h, sensor_w, sensor_h;
    INT32U num_sensors = NUM_SENSOR;
    gpCdspFmt_t format;

    // set sensor size
    DBG_PRINT("%s = %d\r\n", __func__, index);

    g_sensor_info_idx = index;

    //Enabel mipi clk, set mipi clk
    if(imx307_mipi_cfg.pixel_clk_sel == GENERATE_PIXEL_CLK)
    {
        drv_l2_mipi_ctrl_set_clk(ENABLE, MIPI_CLK_DIV);
        osDelay(100);
    }

    // set cdsp format
#if BINMODE_OUT
    format.image_source = C_CDSP_BINMODE + MIPI_DEV_NO;
#elif MIPI_DEV_NO == 0
    format.image_source = C_CDSP_MIPI;
#else
    format.image_source = C_CDSP_MIPI1;
#endif

    //format.image_source = C_CDSP_BINMODE;//binmode path

    format.input_format =  imx307_cdsp_mipi_ops.info[index].input_format;
    format.output_format = imx307_cdsp_mipi_ops.info[index].output_format;
    target_w = imx307_cdsp_mipi_ops.info[index].target_w;
    target_h = imx307_cdsp_mipi_ops.info[index].target_h;
    if((format.image_source == C_CDSP_BINMODE)||(format.image_source == C_CDSP_BINMODE1))
    {
        //use binmode input, cdsp use target size, sensor size would larger than target size,
        //binmode use by2, by4, crop, to scale down input, so dont need cdsp scale size here
        format.hpixel = sensor_w = imx307_cdsp_mipi_ops.info[index].target_w;
        format.vline = sensor_h = imx307_cdsp_mipi_ops.info[index].target_h;
        DBG_PRINT("cdsp set binmode!!!\r\n");
    }
    else
    {
        format.hpixel = sensor_w = imx307_cdsp_mipi_ops.info[index].sensor_w;
        format.vline = sensor_h = imx307_cdsp_mipi_ops.info[index].sensor_h;
    }
    format.hoffset = imx307_cdsp_mipi_ops.info[index].hoffset;
    format.voffset = imx307_cdsp_mipi_ops.info[index].voffset;
    format.sensor_timing_mode = imx307_cdsp_mipi_ops.info[index].interface_mode;
    format.sensor_hsync_mode = imx307_cdsp_mipi_ops.info[index].hsync_active;
    format.sensor_vsync_mode = imx307_cdsp_mipi_ops.info[index].vsync_active;
    DBG_PRINT("cdsp set normal mode!!!\r\n");

    if(drv_l2_cdsp_set_fmt(&format, num_sensors) < 0)
    {
        DBG_PRINT("cdsp set fmt err!!!\r\n");
    }

    drv_l1_CdspSetDataSource(SDRAM_INPUT);

    // set scale down
    if(((sensor_w > target_w) || (sensor_h > target_h)) && (docropflag == 0))
    {
        drv_l2_cdsp_set_yuv_scale(target_w, target_h);
    }
    else if(((sensor_w > target_w) || (sensor_h > target_h)) && (docropflag == 1))
    {
        INT32U point_x = 16, point_y = 16;
        drv_l1_CdspSetCrop(point_x, point_y, target_w, target_h);
        drv_l1_CdspSetCropEn(docropflag); //1:Enable, 0:Disable
    }

    // cdsp start
    drv_l2_CdspTableRegister((gpCisCali_t*)&g_cali, CDSP_IDX);

    drv_l2_cdsp_stream_on(ENABLE, bufA, bufB, num_sensors);
    drv_l2_cdsp_analog_gain_thr_init(GainThrTable);
    drv_l2_cdsp_enable((gpUserFav_t *)&g_FavTable, sensor_w, sensor_h, target_w, target_h, CDSP_IDX);
    drv_l2_cdsp_sat_contrast_reinit_thr();

    //mipi start
    drv_l1_mipi_set_parameter(MIPI_DEV_NO, &imx307_mipi_cfg);
#ifdef MIPI_ISR_TEST
    drv_l1_mipi_B_isr_register(mipi_imx307_handle);
    drv_l1_mipi_set_irq_enable(MIPI_DEV_NO, ENABLE, MIPI_SOF);
#endif

    //Enable MCLK & Init Sensor
    imx307_mipi_sensor_init();

    // reset sensor ev idx
    seInfo.ae_ev_step = 0;
    imx307_set_xfps_exposure_time(&seInfo);

    drv_l1_CdspSetDataSource(CdspDev->imgSrc);
    DBG_PRINT("sony imx307 cdsp mipi init done!!\r\n");
}

