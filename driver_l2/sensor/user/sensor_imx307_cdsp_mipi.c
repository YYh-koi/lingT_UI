static INT32S imx307_sccb_write_table(regval16_t *pTable)
{
    INT8U retry_cnt=0;

    while(1)
    {
        if (pTable->reg_num == 0 && pTable->value == 0)
            break;

        DBG_PRINT("0x%04x, 0x%02x\r\n", pTable->reg_num, pTable->value);
        //DBG_PRINT("*");
        if(imx307_sccb_write(pTable->reg_num, pTable->value) < 0)
        {
            DBG_PRINT("%s: sccb write fail: reg = 0x%04x, val = 0x%02x\r\n", __FUNCTION__, pTable->reg_num, pTable->value);
            retry_cnt += 1;
            if(retry_cnt >= 10)
                return STATUS_FAIL;
            continue;
        }

		pTable++;
	}
	return STATUS_OK;
}

static int imx307_set_xfps_exposure_time(sensor_exposure_t *si)
{
    int idx, temp;
    unsigned char SHS1_7_0, SHS1_15_8, SHS1_17_16;
    static int old_gain = 0, old_time = 0;

    si->sensor_ev_idx += si->ae_ev_step;
    if(si->sensor_ev_idx >= si->max_ev_idx) si->sensor_ev_idx = si->max_ev_idx;
    if(si->sensor_ev_idx < 0) si->sensor_ev_idx = 0;

    idx = si->sensor_ev_idx * 3;

    si ->time = p_expTime_table[idx];
    si ->analog_gain = p_expTime_table[idx+1];
    si ->digital_gain = p_expTime_table[idx+2];
    //DBG_PRINT("[EV=%d, offset=%d]: time = 0x%x, analog gain =0x%x\r\n", si->sensor_ev_idx, si->ae_ev_step, si->time, si->analog_gain);
    //DBG_PRINT("[EV=%d, offset=%d]: time = %d, analog gain =%d\r\n", si->sensor_ev_idx, si->ae_ev_step, si->time, si->analog_gain);
    if((old_time != si->time)||(old_gain != si->analog_gain))
    {
        //DBG_PRINT("set time \r\n");
        temp = 1125-si->time;
        SHS1_7_0 = (unsigned char)(temp & 0xFF);
        SHS1_15_8 = (unsigned char)((temp>>8) & 0xFF);
        SHS1_17_16 = (unsigned char)((temp>>16) & 0x3);
        imx307_sccb_write(0x3020, SHS1_7_0);
        imx307_sccb_write(0x3021, SHS1_15_8);
        imx307_sccb_write(0x3022, SHS1_17_16);
        old_time = si->time;
    }

    if(old_gain != si->analog_gain)
    {
        // DBG_PRINT("set gain \r\n");
        imx307_sccb_write(0x3014,  si->analog_gain);
        old_gain = si->analog_gain;
    }

    //seInfo.ae_ev_idx = 0;
    return 0;
}

